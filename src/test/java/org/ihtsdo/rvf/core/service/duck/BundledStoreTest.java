package org.ihtsdo.rvf.core.service.duck;

import org.ihtsdo.rvf.core.data.model.Assertion;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The bundled store ({@code duck/store.json}, generated by the build from the corpus
 * checkout) is internally consistent and was built from the corpus this build checked out.
 */
class BundledStoreTest {

	/** Where {@code checkout-resources.sh} clones the assertion corpus. */
	private static final Path CORPUS = Path.of("snomed-release-validation-assertions");

	private static DuckStore store;

	@BeforeAll
	static void load() throws IOException {
		store = new DuckStoreLocator("").load();
	}

	@Test
	void theDeclaredIdentityVerifies() throws IOException {
		DuckStore.PackRecord identity = store.identity().orElseThrow(
				() -> new AssertionError("the bundled store has no pack identity, so reports cannot name it"));
		assertEquals(store.assertionDigest(), identity.digest());
		assertFalse(identity.name().isBlank());
		assertFalse(identity.version().isBlank());
		assertEquals(store.assertions().size(), identity.assertions());
	}

	@Test
	void itWasBuiltFromTheCorpusThisBuildCheckedOut() throws Exception {
		// The MySQL engine imports this checkout; the DuckDB engine must run the same commit.
		assertTrue(store.corpusRef().matches("[0-9a-f]{40}"), "corpusRef: " + store.corpusRef());
		assertEquals(corpusHead(), store.corpusRef(),
				"the bundled store was not built from " + CORPUS.toAbsolutePath() + "; rebuild");
	}

	@Test
	void itIsNotTruncated() {
		// No assertions means no findings, which reads as a clean pass.
		assertTrue(store.assertions().size() > 300,
				"bundled store looks truncated: " + store.assertions().size() + " assertions");
	}

	@Test
	void everyAssertionHasAFileASourceHashAndStatements() {
		// The exception: resource scripts that only define a MySQL function or procedure
		// compile to nothing; the store's ports stand in for them.
		List<String> broken = new ArrayList<>();
		for (DuckStore.StoredAssertion a : store.assertions().values()) {
			boolean definitionOnly = "resource".equals(a.keywords()) && a.statements().isEmpty();
			if (a.file().isBlank() || !a.sha256().matches("[0-9a-f]{16}")
					|| (a.statements().isEmpty() && !definitionOnly)) {
				broken.add(a.uuid() + " " + a.file());
			}
		}
		assertEquals(List.of(), broken);
		assertFalse(store.ports().isEmpty());
	}

	@Test
	void itCarriesBothGroupingFilesAndTheirHashesMatchTheirText() {
		assertEquals(Set.of(DuckAssertionSource.GROUPS_XML, DuckAssertionSource.POLICIES_XML),
				store.grouping().keySet());
		for (DuckStore.GroupingFile file : store.grouping().values()) {
			assertTrue(file.sha256().matches("[0-9a-f]{16}"), file.file() + ": " + file.sha256());
			assertEquals(DuckStore.sha256Hex(file.text()).substring(0, file.sha256().length()), file.sha256(),
					file.file() + " was edited after it was hashed");
		}
	}

	@Test
	void theStandardGroupsSelectAssertions() throws IOException {
		DuckAssertionSource source = DuckAssertionSource.from(store);
		for (String group : List.of("file-centric-validation", "component-centric-validation",
				"release-type-validation", "common-edition", "InternationalEdition")) {
			assertFalse(source.getAssertionsInGroups(List.of(group)).isEmpty(), group + " selects nothing");
		}
		List<Assertion> international = source.getAssertionsInGroups(List.of("InternationalEdition"));
		assertTrue(international.size() > 200, "InternationalEdition selects " + international.size());
		assertFalse(source.getAssertionsByKeyWords("resource", true).isEmpty(),
				"the resource assertions that build shared tables are present");
	}

	private static String corpusHead() throws Exception {
		assertTrue(Files.isRegularFile(CORPUS.resolve("manifest.xml")), "no corpus checkout at " + CORPUS.toAbsolutePath());
		Process git = new ProcessBuilder("git", "-C", CORPUS.toString(), "rev-parse", "HEAD")
				.redirectErrorStream(true).start();
		String out = new String(git.getInputStream().readAllBytes(), StandardCharsets.UTF_8).trim();
		assertTrue(git.waitFor(30, TimeUnit.SECONDS) && git.exitValue() == 0, "git rev-parse HEAD: " + out);
		return out;
	}
}
